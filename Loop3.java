/* using the for-loop */

public class Loop3 {

    public static void main(String[] args) {

        // arg 1 = initialization; arg 2 = condition; arg 3 = iteration
        for (int intCounter = 1; intCounter <= 10; intCounter++) {

            System.out.print(intCounter + " ");

        }  // for (int intCounter = 1; intCounter <= 10; intCounter++)

    }  // public static void main(String[] args)

}  // public class Loop3