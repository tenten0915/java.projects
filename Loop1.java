public class Loop1 {

    public static void main(String[] args) {

        int intRepeat = 2;

        do {
            System.out.println("\nThis will execute");
            System.out.println("  more than once..");
  
            intRepeat--;
        } while (intRepeat < 3 && intRepeat >= 1);

    }  // public static void main(String[] args)

}  // public class Loop1