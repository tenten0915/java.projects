/* using the while-loop statement */

public class Loop2 {

    public static void main(String[] args) {

        int intCountdown = 9;

        while (intCountdown < 10 && intCountdown >= 1) {

            System.out.println(intCountdown);
            intCountdown--;

        }  // while (intCountdown < 10 && intCountdown >= 1)
 
    }  // public static void main(String[] args)

}  // public class Loop2